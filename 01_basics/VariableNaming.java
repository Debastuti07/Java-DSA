public class VariableNaming {
    public static void main(String[] args) {
        int megha=25;//valid variable;
        int _a=25;//valid variable;
        int $b=8;//valid variable
        // int 1x=5;//invalid
        System.out.println(megha);
        System.out.println(_a);
        System.out.println($b);

        //either "start" with "_" or "$" in the special character 
        // no gap between the variable name 
        //don't use the "datatype" , "class", "for" etc as variable name 

        
    }
}
