public class Variable {
    public static void main(String[] args) {
        int x=5;
        System.out.println(x+7);//12
        int y; //declaration
        y=20; //initialization
        System.out.println(y);//20
        System.out.println(x*y);//100
        
        x=7;
        x=x-5;
        System.out.println(x);//2

        x=x-30;
        System.out.println(x);//-28

        x=x/25;
        System.out.println(x);//-1
    }   
}
