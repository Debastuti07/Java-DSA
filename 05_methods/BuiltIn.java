public class BuiltIn {
    public static void main(String[] args) {
        double x=Math.PI;
        System.out.println(x);
        System.out.println(Math.sqrt(4));//square root
        System.out.println(Math.cbrt(8));//cube root
        System.out.println(Math.abs(-8));//absolute Value
        System.out.println(Math.floor(-6.8));//greatest integer Value
        System.out.println(Math.ceil(6.8));//roundoff integer Value
        System.out.println(Math.min(2,3));//min Value
        System.out.println(Math.max(2,3));//max Value

        int p=(Math.max(2,3 ));
        System.out.println(Math.max(p,4 ));

    }
}

